"""Domain records for the game platform.

Records are immutable: the service builds updated copies with `dataclasses.replace` and
writes them back to the store, so a store never shares mutable state with its callers.
"""

import datetime as dt
from dataclasses import dataclass
from typing import Final, Literal

from pydantic import JsonValue

MIN_PLAYERS: Final = 1
MAX_PLAYERS: Final = 10

MatchStatus = Literal["waiting_for_players", "ongoing", "over"]
SeatKind = Literal["human", "computer"]
EndReason = Literal["finished", "player_left"]


LinkedAccountKind = Literal["google", "phone", "email"]


@dataclass(frozen=True, kw_only=True)
class LinkedAccount:
    """A third-party login linked to a user: a Google subject, a verified
    phone number (E.164), or a verified email address (lowercased)."""

    kind: LinkedAccountKind
    identifier: str
    linked_at: dt.datetime


@dataclass(frozen=True, kw_only=True)
class User:
    id: str
    display_name: str
    # Filled from the login provider when it shares them (Google shares name,
    # email and profile picture). Defaults to empty so older data files load.
    email: str = ""
    picture_url: str = ""
    # The language the user chose (a code from i18n.LOCALE_CODES); empty means none
    # chosen, so each request's Accept-Language decides. Defaults to empty so older data
    # files load.
    locale: str = ""
    # Generated by the server and kept as is, in memory and in the data file. The API
    # returns it from [POST /users] and the debug tools only.
    password: str
    # Defaults to empty so data files written before linked accounts existed still load.
    linked_accounts: tuple[LinkedAccount, ...] = ()
    # Set when this account was merged into another one. A replaced user is
    # never deleted (so old credentials keep authenticating), but every use of
    # it resolves to the surviving user. A replaced user holds no games,
    # matches, seats, moves, or linked accounts. Defaults to None so older data
    # files still load.
    replaced_by_user_id: str | None = None
    # The ids of every user this account replaced, oldest first. Merges always
    # flatten: when this user absorbs S, everyone S had replaced is repointed
    # directly at this user, so there are never replacement chains. Defaults to
    # empty so older data files still load.
    replaced_user_ids: tuple[str, ...] = ()
    # The user whose invite link brought this user here, recorded once, when the
    # account is created (see GamePlatform.create_user). None for users who came
    # without an invite link. It may name an account that was later merged into
    # another one; GamePlatform.invite_stats resolves it to the survivor.
    # Defaults to None so older data files still load.
    invited_by_user_id: str | None = None
    # The match invite (Invite.token) the account was created through, if any, so
    # the invite can tell sign-ups from existing users. Defaults to None so older
    # data files load.
    invited_via_invite_token: str | None = None
    # Games the user saved to their library, most recently saved last. Defaults to
    # empty so older data files load.
    saved_game_ids: tuple[str, ...] = ()
    token_balance: int = 0
    last_token_grant_day: str | None = None
    created_at: dt.datetime
    updated_at: dt.datetime


@dataclass(frozen=True, kw_only=True)
class GameRules:
    """The parts of a game that the server enforces during a match."""

    allowed_player_counts: tuple[int, ...]
    allows_leave_mid_match: bool
    allows_join_mid_match: bool

    @property
    def max_players(self) -> int:
        return max(self.allowed_player_counts)


@dataclass(frozen=True, kw_only=True)
class Game:
    """One version of a game. Every update creates a new version."""

    id: str
    # Starts at 1 and increases by one with every update.
    version: int
    owner_user_id: str
    name: str
    description: str
    rules: GameRules
    # The game's client code (the innerHTML of its sandboxed iframe). The server never
    # executes it.
    code: str
    created_at: dt.datetime
    updated_at: dt.datetime
    # Applies to the whole game, so it is set on every version read back from the store
    # once the game is deleted. Deleted games are kept because matches may use them.
    deleted: bool = False
    # Current game-wide visibility, applied to every version read from the store.
    published: bool = True


@dataclass(frozen=True, kw_only=True)
class GameDraft:
    """Owner-only working copy. Its id becomes the public game id on publication."""

    id: str
    owner_user_id: str
    name: str
    description: str
    rules: GameRules
    code: str
    created_at: dt.datetime
    updated_at: dt.datetime
    base_version: int = 0
    revision: int = 1


AgentMessageRole = Literal["user", "assistant"]


@dataclass(frozen=True, kw_only=True)
class AgentConversationEntry:
    """One message exchanged with the game-building agent about one game."""

    role: AgentMessageRole
    text: str
    created_at: dt.datetime
    # The game's published version when the message was exchanged; 0 while the
    # game had never been published (it existed only as a draft).
    game_version: int


@dataclass(frozen=True, kw_only=True)
class AgentConversation:
    """The whole recorded agent conversation for one game (or draft), oldest
    first. Admin-only: it is never part of a game or draft API response."""

    game_id: str
    entries: tuple[AgentConversationEntry, ...] = ()


@dataclass(frozen=True, kw_only=True)
class Seat:
    player_index: int
    kind: SeatKind
    # Set exactly when [kind] is "human".
    user_id: str | None


@dataclass(frozen=True, kw_only=True)
class Move:
    move_number: int
    player_index: int
    made_by_user_id: str
    created_at: dt.datetime
    new_state: JsonValue
    # The seats that may make the next move; [None] ends the match.
    next_turn_player_indices: frozenset[int] | None


@dataclass(frozen=True, kw_only=True)
class Match:
    id: str
    game_id: str
    owner_user_id: str
    # The game version the match was created with. Its rules (and code) apply for the
    # whole match, even if the game is later updated or deleted.
    game_version: int
    status: MatchStatus
    seats: tuple[Seat, ...]
    state: JsonValue
    # The seats that may move now; [None] when the match isn't ongoing.
    turn_of_player_indices: frozenset[int] | None
    end_reason: EndReason | None
    moves: tuple[Move, ...]
    # Non-owners who "deleted" this match after it ended; it is excluded from their
    # match list only.
    hidden_for_user_ids: frozenset[str]
    created_at: dt.datetime
    updated_at: dt.datetime
    # A private match is left out of open-match listings and matchmaking, and only
    # its players and people with an invite link can see or join it. Defaults to
    # False so older data files load.
    private: bool = False
    # The match created as a replay of this match, if any.
    rematch_match_id: str | None = None
    # Set on matches created by matchmaking (a quick match with random opponents):
    # the number of players it waits for. The match starts by itself when that many
    # have joined. Defaults to None so older data files load.
    matchmaking_player_count: int | None = None

    # None turn means this legacy match has no recorded starting snapshot.
    initial_state: JsonValue = None
    initial_turn_player_indices: frozenset[int] | None = None
    bet_per_player: int = 0
    token_pot: int = 0
    token_payouts: dict[int, int] | None = None

    def seat_of(self, user_id: str) -> Seat | None:
        return next((seat for seat in self.seats if seat.user_id == user_id), None)

    @property
    def human_user_ids(self) -> tuple[str, ...]:
        return tuple(seat.user_id for seat in self.seats if seat.user_id is not None)

    @property
    def num_computer_opponents(self) -> int:
        return sum(1 for seat in self.seats if seat.kind == "computer")

    def involves(self, user_id: str) -> bool:
        return user_id == self.owner_user_id or self.seat_of(user_id) is not None


@dataclass(frozen=True, kw_only=True)
class InviteAcceptance:
    """Someone who opened an invite link and took a seat (or signed up) with it."""

    user_id: str
    accepted_at: dt.datetime
    # True when the account was created through this invite (a referral sign-up).
    signed_up: bool = False


@dataclass(frozen=True, kw_only=True)
class Invite:
    """A shareable link (or QR code) to one match. The token is the secret: whoever
    has it can see the match and take a seat, even in a private match."""

    token: str
    match_id: str
    created_by_user_id: str
    created_at: dt.datetime
    # None means no expiry.
    expires_at: dt.datetime | None = None
    # None means unlimited.
    max_uses: int | None = None
    revoked: bool = False
    # Who used the invite, oldest first; the referral record.
    acceptances: tuple[InviteAcceptance, ...] = ()
    # How many times the link was opened (GET /invites/{token}), whether or not
    # anyone joined; the top of the referral funnel.
    views: int = 0


@dataclass(frozen=True, kw_only=True)
class WebPushSubscription:
    """A browser's web push subscription, bound to a user.

    The endpoint and keys are the browser's push credentials: anyone holding them
    can send pushes to that browser, so they're kept as carefully as passwords.
    """

    id: str
    user_id: str
    # The push service's URL for this browser. Unique: one browser profile has one
    # endpoint, whoever is logged into it.
    endpoint: str
    # The browser's P-256 public key and auth secret (base64url), used to encrypt
    # payloads for this subscription (RFC 8291).
    p256dh: str
    auth: str
    # When the browser says the subscription lapses; None means it didn't say.
    expiration_time: dt.datetime | None = None
    created_at: dt.datetime
    updated_at: dt.datetime
